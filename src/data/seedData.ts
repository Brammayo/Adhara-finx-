function buildCalendarCycle(
  annualPremium: number,
  entries: Array<{
    year: number;
    month: number;
    status: CalendarMonthEntry['status'];
    settledCycleYear?: number;
    receiptId?: string;
  }>
): CalendarMonthEntry[] {
  const calc = calculateContribution(annualPremium);
  return entries.map((e) => ({
    year: e.year,
    month: e.month,
    status: e.status,
    baseAmount: calc.monthlyBase,
    totalDebited: calc.totalMonthly,
    settledCycleYear: e.settledCycleYear,
    receiptId: e.receiptId,
  }));
}

function buildTransactionsForPolicy(
  policy: PolicyRecord,
  historyMonths: Array<{
    year: number;
    month: number;
    status: 'Paid' | 'Pending' | 'Failed';
    note?: string;
  }>,
  settlementRecord?: { date: string; amount: number; receiptCode: string }
): LedgerTransaction[] {
  const calc = calculateContribution(policy.annualPremium);
  const txs: LedgerTransaction[] = historyMonths.map((item, idx) => {
    const day = '05';
    const mm = String(item.month + 1).padStart(2, '0');
    return {
      id: `TX-${policy.id}-${item.year}${mm}-${idx}`,
      policyId: policy.id,
      customerId: policy.customerId,
      date: `${item.year}-${mm}-${day}`,
      monthLabel: `${MONTH_NAMES_SHORT[item.month]} ${item.year}`,
      type: 'Monthly Contribution',
      baseAmount: calc.monthlyBase,
      platformFee: calc.platformFee,
      gatewayFee: calc.gatewayFee,
      totalAmount: calc.totalMonthly,
      status: item.status,
      receiptCode: `AFX-DEMO-${policy.id.slice(-3)}-${item.year}${mm}`,
      note: item.note,
    };
  });

  if (settlementRecord) {
    txs.push({
      id: `TX-SET-${policy.id}`,
      policyId: policy.id,
      customerId: policy.customerId,
      date: settlementRecord.date,
      monthLabel: 'Annual Cycle Settlement',
      type: 'Annual Settlement',
      baseAmount: settlementRecord.amount,
      platformFee: 0,
      gatewayFee: 0,
      totalAmount: settlementRecord.amount,
      status: 'Settled',
      receiptCode: settlementRecord.receiptCode,
      note: `DEMO Annual settlement disbursed to ${policy.insuranceCompany}`,
    });
  }

  return txs;
}

